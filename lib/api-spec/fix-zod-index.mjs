// orval re-generates lib/api-zod/src/index.ts on every run and appends
// `export * from './generated/types'`. That line breaks the build: for
// multipart operations orval emits a zod schema const with the exact same
// name as the TS type (e.g. UploadVideoFileBody), so re-exporting both
// modules triggers TS2308. Rewrite the barrel deterministically after each
// codegen run. Consumers needing raw types can deep-import generated/types.
import { writeFileSync } from "node:fs";
import { dirname, resolve } from "node:path";
import { fileURLToPath } from "node:url";

const here = dirname(fileURLToPath(import.meta.url));
const target = resolve(here, "../api-zod/src/index.ts");

const content = `// Zod schemas generated by orval. The raw TS types under ./generated/types
// are intentionally NOT re-exported: for multipart operations orval emits a
// zod schema const with the exact same name as the TS type (e.g.
// UploadVideoFileBody), and re-exporting both causes TS2308. Consumers that
// need the raw types can deep-import "./generated/types".
export * from "./generated/api";
`;

writeFileSync(target, content);
console.log("fix-zod-index: rewrote lib/api-zod/src/index.ts");
